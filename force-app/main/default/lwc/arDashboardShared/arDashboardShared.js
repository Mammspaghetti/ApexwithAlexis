const AXIS_NOUNS = {
  bm: LBL.NounBm,
  entity: LBL.NounEntity,
  perimeter: LBL.NounPerimeter,
  group: LBL.NounGroup
};

/** Nom de l'axe en minuscules pour les titres (« Par agence »). */
export function axisNoun(axis) {
  return AXIS_NOUNS[axis] || AXIS_NOUNS.entity;
}

/** Remplace {0}, {1}… (même convention que c/arI18n.formatLabel, sans dépendance). */
export function fill(template, ...values) {
  return String(template).replace(/\{(\d+)\}/g, (match, index) => {
    const value = values[Number(index)];
    return value === undefined ? match : String(value);
  });
}

/** Pourcentage à 1 décimale, virgule ; « — » pour une valeur absente (échantillon sous le minimum). */
export function pct(value) {
  return formatPercent(value);
}

/** Nombre à 1 décimale, virgule (jours, points de MC2) ; « — » si absent. */
export function decimal1(value) {
  if (value === null || value === undefined || Number.isNaN(Number(value))) {
    return "—";
  }
  return Number(value).toLocaleString("fr-FR", {
    minimumFractionDigits: 1,
    maximumFractionDigits: 1
  });
}

export function days(value) {
  return value === null || value === undefined
    ? "—"
    : fill(LBL.Days, decimal1(value));
}

export function monthLabel(key, lang) {
  const [year, month] = String(key).split("-").map(Number);
  return new Date(year, month - 1, 1).toLocaleDateString(lang || "fr-FR", {
    month: "short",
    year: "2-digit"
  });
}

/** Largeur de barre en % (bornée) pour un style en ligne. */
export function width(value) {
  const n = Number(value);
  return Number.isFinite(n) ? Math.max(0, Math.min(100, n)) : 0;
}